from .nodes import BinaryExpression, CallExpression, Expression, IdentifierExpression, IntegerLiteral, LetStatement, Program, ReturnStatement
from .diagnostics import InternalCompilerError

# Compiler-generated LLVM names live under a reserved prefix. The OCL lexer
# cannot produce '.' in an identifier, so nothing a user writes can collide with
# a generated name. Numbered temporaries are safe for the same reason: an OCL
# identifier can never begin with a digit.
GENERATED_PREFIX = "ocl."
ENTRY_LABEL = f"{GENERATED_PREFIX}entry"


def _escape_llvm_string(value: str) -> str:
    """Encode UTF-8 bytes for an LLVM quoted string."""
    return "".join(
        chr(byte) if 0x20 <= byte <= 0x7E and byte not in (0x22, 0x5C) else f"\\{byte:02X}"
        for byte in value.encode("utf-8")
    )


def generate_llvm_ir(program: Program, source_name: str = "input.ocl") -> str:
    """Lower a program that has already passed `semantic.analyze`."""
    lines = [
        "; Generated by oclc 0.3",
        f'source_filename = "{_escape_llvm_string(source_name)}"',
        "",
    ]
    for function in program.functions:
        if not function.body or not isinstance(function.body[-1], ReturnStatement):
            raise InternalCompilerError(
                f"function '{function.name}' reached codegen without a final return statement; "
                "semantic analysis must run before lowering"
            )
        parameters = ", ".join(f"i32 %{parameter.name}" for parameter in function.parameters)
        body_lines: list[str] = []
        temporary = [0]
        values = {parameter.name: f"%{parameter.name}" for parameter in function.parameters}
        for statement in function.body[:-1]:
            if not isinstance(statement, LetStatement):
                raise InternalCompilerError(f"unsupported statement reached codegen: {type(statement).__name__}")
            values[statement.name] = _lower_expression(statement.initializer, body_lines, temporary, values)
        value = _lower_expression(function.body[-1].expression, body_lines, temporary, values)
        lines.extend((f"define i32 @{function.name}({parameters}) {{", f"{ENTRY_LABEL}:", *body_lines, f"  ret i32 {value}", "}", ""))
    return "\n".join(lines)


def _operands(expression: Expression) -> tuple[Expression, ...]:
    if isinstance(expression, BinaryExpression):
        return (expression.left, expression.right)
    if isinstance(expression, CallExpression):
        return expression.arguments
    return ()


def _lower_expression(expression: Expression, lines: list[str], temporary: list[int], values: dict[str, str]) -> str:
    """Lower one expression to an SSA operand.

    Walks the tree with an explicit stack. Expression depth is bounded only by
    the source, so recursing here would turn a large but valid program into a
    RecursionError instead of a compiled binary.
    """
    results: dict[int, str] = {}
    pending: list[tuple[Expression, bool]] = [(expression, False)]
    while pending:
        node, operands_ready = pending.pop()
        if not operands_ready:
            if isinstance(node, IntegerLiteral):
                results[id(node)] = str(node.value)
                continue
            if isinstance(node, IdentifierExpression):
                try:
                    results[id(node)] = values[node.name]
                except KeyError as error:
                    raise InternalCompilerError(f"unresolved identifier reached codegen: {node.name}") from error
                continue
            if not isinstance(node, (BinaryExpression, CallExpression)):
                raise InternalCompilerError(f"unsupported expression reached codegen: {type(node).__name__}")
            # Revisit this node once its operands have been lowered, and push
            # them reversed so they are emitted left to right. A call with no
            # arguments simply has nothing to push.
            pending.append((node, True))
            pending.extend((operand, False) for operand in reversed(_operands(node)))
            continue
        result = f"%{temporary[0]}"
        temporary[0] += 1
        if isinstance(node, BinaryExpression):
            left = results[id(node.left)]
            right = results[id(node.right)]
            # No nsw/nuw: Prototype 0.3 implements i32 arithmetic as wrapping,
            # so overflow must stay defined rather than become LLVM poison. The
            # permanent profile-specific overflow policy remains provisional.
            instruction = {"+": "add", "-": "sub", "*": "mul"}.get(node.operator)
            if instruction is None:
                raise InternalCompilerError(f"unsupported binary operator reached codegen: {node.operator}")
            lines.append(f"  {result} = {instruction} i32 {left}, {right}")
        elif isinstance(node, CallExpression):
            rendered = ", ".join(f"i32 {results[id(argument)]}" for argument in node.arguments)
            lines.append(f"  {result} = call i32 @{node.callee}({rendered})")
        else:
            raise InternalCompilerError(f"unsupported expression reached codegen: {type(node).__name__}")
        results[id(node)] = result
    return results[id(expression)]
